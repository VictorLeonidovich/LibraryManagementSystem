package com.kvl.library.service.book;

import java.util.List;

/**
 * Сервис для ведения и анализа метрик популярности книг.
 * <p>
 * Обеспечивает изолированное управление статистическими показателями
 * во внешнем хранилище данных без прямого влияния на реляционную модель.
 */
public interface BookPopularityService {

    /**
     * Инкрементировать счетчик просмотров книги.
     *
     * @param isbn международный стандартный книжный номер произведения
     */
    void incrementView(String isbn);

    /**
     * Исключить книгу из общего рейтинга популярности.
     *
     * @param isbn международный стандартный книжный номер произведения
     */
    void removeBook(String isbn);

    /**
     * Получить список самых популярных кодов ISBN в соответствии со статистикой просмотров.
     *
     * @param limit максимальное количество записей в выборке
     * @return список строк с кодами популярных книг
     */
    List<String> getTopBooks(int limit);
}